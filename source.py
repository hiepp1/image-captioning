def _clean_caption_for_bleu_evaluation(caption_string):
    return [
        word for word in caption_string.lower().split()
        if word not in ['<bos>', '<eos>', '<BOS>', '<EOS>', 'bos', 'eos']
    ]

def evaluate_bleu_score(model, df, features, tokenizer=tokenizer, max_length=max_length, num_samples=10):
    image_to_cleaned_refs = {}
    unique_images = df['image'].unique()

    for img_filename in unique_images:
        raw_captions = df.loc[df['image'] == img_filename, 'cleaned_caption'].tolist()
        cleaned_refs_for_image = []
        for cap_str in raw_captions:
            cleaned_words = _clean_caption_for_bleu_evaluation(cap_str)
            if cleaned_words:
                cleaned_refs_for_image.append(cleaned_words)
        if cleaned_refs_for_image:
            image_to_cleaned_refs[img_filename] = cleaned_refs_for_image

    sampled_image_ids = np.random.choice(list(image_to_cleaned_refs.keys()), min(num_samples, len(image_to_cleaned_refs)), replace=False)

    actual_corpora = []
    predicted_corpora = []

    smoothie = SmoothingFunction().method4

    for image_filename in tqdm(sampled_image_ids, desc="Generating captions"):
        actual_captions_for_image = image_to_cleaned_refs[image_filename]
        predicted_caption_str = predict_caption(model=model, image=image_filename, features=features)
        predicted_caption_words = predicted_caption_str.split()

        actual_corpora.append(actual_captions_for_image)
        predicted_corpora.append(predicted_caption_words)

    print('\nBLEU-1: %f' % corpus_bleu(actual_corpora, predicted_corpora, weights=(1.0, 0, 0, 0), smoothing_function=smoothie))
    print('BLEU-2: %f' % corpus_bleu(actual_corpora, predicted_corpora, weights=(0.5, 0.5, 0, 0), smoothing_function=smoothie))
    print('BLEU-3: %f' % corpus_bleu(actual_corpora, predicted_corpora, weights=(0.333, 0.333, 0.333, 0), smoothing_function=smoothie))
    print('BLEU-4: %f' % corpus_bleu(actual_corpora, predicted_corpora, weights=(0.25, 0.25, 0.25, 0.25), smoothing_function=smoothie))

