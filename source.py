batch_size = 64
X_col = 'image'
y_col = 'cleaned_caption'

class CustomDataGenerator(Sequence):
    def __init__(self, df, features, X_col=X_col, y_col=y_col, batch_size=batch_size, tokenizer=tokenizer, vocab_size=vocab_size, max_length=max_length, shuffle=True):
      self.df = df.copy()
      self.X_col = X_col
      self.y_col = y_col
      self.batch_size = batch_size
      self.tokenizer = tokenizer
      self.vocab_size = vocab_size
      self.max_length = max_length
      self.features = features
      self.shuffle = shuffle
      self.n = len(self.df)

    def on_epoch_end(self):
      if self.shuffle:
        self.df = self.df.sample(frac=1).reset_index(drop=True)

    def __len__(self):
      return self.n // self.batch_size

    def __getitem__(self, index):
      batch = self.df.iloc[index * self.batch_size:(index + 1) * self.batch_size, :]
      X1, X2, y = self.__get_data(batch)
      return (X1, X2), y

    def __get_data(self, batch):
      X1, X2, y = list(), list(), list()
      images_in_batch = batch[self.X_col].tolist()

      for image_id in images_in_batch:
        feature = self.features[image_id][0]
        captions = batch.loc[batch[self.X_col] == image_id, self.y_col].tolist()
        for caption in captions:
          seq = self.tokenizer.texts_to_sequences([caption])[0]
          for i in range(1, len(seq)):
            in_seq, out_seq = seq[:i], seq[i]
            in_seq = pad_sequences([in_seq], maxlen=self.max_length)[0]
            out_seq = to_categorical([out_seq], num_classes=self.vocab_size)[0]
            X1.append(feature)
            X2.append(in_seq)
            y.append(out_seq)

      X1, X2, y = np.array(X1), np.array(X2), np.array(y)
      return X1, X2, y

