def idx_to_word(idx, tokenizer=tokenizer):
    for word, i in tokenizer.word_index.items():
        if i == idx:
            return word
    return None

def preprocess_img(img_path, img_size=224):
  img = load_img(img_path, target_size=(img_size, img_size))
  img = img_to_array(img)
  img = img / 255.
  img = np.expand_dims(img, axis=0)
  return img

def get_image_feature(img_path):
  img = preprocess_img(img_path)
  feature = fe.predict(img, verbose=0)
  return feature

def predict_caption(model, image, features=None, tokenizer=tokenizer, max_length=max_length):
    in_text = 'bos'

    if features:
      feature = features[image]
    else:
      feature = get_image_feature(image)

    for i in range(max_length):
        # encode input sequence
        sequence = tokenizer.texts_to_sequences([in_text])[0]
        # pad the sequence
        sequence = pad_sequences([sequence], max_length)
        # predict next word
        y_pred = model.predict([feature, sequence], verbose=0)
        # get index of the word with high probability
        y_pred = np.argmax(y_pred)
        # convert index to word
        word = idx_to_word(y_pred, tokenizer)

        if word is None:
            break

        in_text += " " + word

        if word == 'eos':
            break
    return in_text.replace('bos ', '').replace(' eos', '').strip()

